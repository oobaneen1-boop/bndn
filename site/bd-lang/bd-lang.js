/* Bandan language switcher · bd-lang v1 (preview, 2026-11-10)
   - Arabic stays the default; nothing is translated until the visitor chooses.
   - Uses Google Website Translator behind a hidden host; Google's bar/banner/tooltips are hidden.
   - Mount: put <div data-bd-lang></div> where the button should sit (e.g. in the header).
     If no slot exists, a small floating button is added at the top corner.
   - Choice is remembered (cookie "googtrans" + localStorage) across all /bndn/ pages. */
(function(){
  'use strict';
  if (window.__bdLang) return; window.__bdLang = true;
  var SRC = 'ar';
  var me = document.currentScript || (function(){var s=document.getElementsByTagName('script');return s[s.length-1]})();
  var BASE = me && me.src ? me.src.replace(/[^\/]*$/,'') : '';
  var STORE = 'bd-lang';
  // Brand words: before machine translation they are swapped for their Latin form so Google keeps them
  // intact (e.g. "نشرة بندن الأحدية" -> "BNDN Sunday Newsletter"). Arabic view is never touched.
  // Extend/override with window.BD_LANG_KEEP = {'وتيرة أنسيات':'Wateera'} before this script.
  var KEEP = {'بندن':'BNDN'}; (function(x){ for(var k in x) KEEP[k]=x[k]; })(window.BD_LANG_KEEP || {});

  // Google Translate language codes. Names are generated by the browser (Intl.DisplayNames),
  // and anything extra Google offers is appended automatically once the widget loads.
  var PINNED = ['en','fr','de','es','tr','fa','ckb','ku','ur','ru','zh-CN','hi'];
  var CODES = ('af sq am hy as ay az bm eu be bn bho bs bg ca ceb ny zh-CN zh-TW co hr cs da dv doi nl en eo et ee tl fi fr fy gl ka de el gn gu ht ha haw iw hi hmn hu is ig ilo id ga it ja jw kn kk km rw gom ko kri ku ckb ky lo la lv ln lt lg lb mk mai mg ms ml mt mi mr mni-Mtei lus mn my ne no or om ps fa pl pt pa qu ro ru sm sa gd nso sr st sn sd si sk sl so es su sw sv tg ta tt te th ti ts tr tk ak uk ur ug uz vi cy xh yi yo zu ' +
               'ab ace ach ba ban br ce cv crh ff fj fur gaa hil iba kg ltg mak mfe nr pag pap os sg shn ss tn to tet tiv tyv udm ve war wo yua zap fa-AF pt-PT').split(' ');
  var RTL = {ar:1,iw:1,he:1,fa:1,'fa-AF':1,ur:1,ps:1,sd:1,ckb:1,ug:1,yi:1,dv:1};
  var BCP = {iw:'he',jw:'jv','zh-CN':'zh-Hans','zh-TW':'zh-Hant','mni-Mtei':'mni','fa-AF':'fa-AF',gom:'kok'};
  var FALLBACK = {ckb:['کوردی (سۆرانی)','الكردية (السورانية)','Kurdish (Sorani)'],ku:['Kurdî (Kurmancî)','الكردية (الكرمانجية)','Kurdish (Kurmanji)'],
    'zh-CN':['中文（简体）','الصينية المبسطة','Chinese (Simplified)'],'zh-TW':['中文（繁體）','الصينية التقليدية','Chinese (Traditional)'],
    'fa-AF':['دری','الدارية','Dari'],'pt-PT':['Português (Portugal)','البرتغالية (البرتغال)','Portuguese (Portugal)'],'mni-Mtei':['ꯃꯩꯇꯩꯂꯣꯟ','المانيبورية','Meiteilon (Manipuri)']};

  function dn(locale, code){ try{ var d=new Intl.DisplayNames([locale],{type:'language'}); var n=d.of(code); return n && n!==code ? n : ''; }catch(e){ return ''; } }
  var cache = {};
  function names(code){
    if (cache[code]) return cache[code];
    var b = BCP[code] || code, f = FALLBACK[code];
    var nat = (f&&f[0]) || dn(b,b) || dn('en',b) || code;
    var ar  = (f&&f[1]) || dn('ar',b) || '';
    var en  = (f&&f[2]) || dn('en',b) || code;
    nat = nat.charAt(0).toLocaleUpperCase(b) + nat.slice(1);
    return (cache[code] = {nat:nat, ar:ar, en:en});
  }

  // ---------- state ----------
  function getCookieLang(){ var m=document.cookie.match(/(?:^|;\s*)googtrans=\/[^\/]*\/([^;]+)/); return m?decodeURIComponent(m[1]):''; }
  function current(){ var c=getCookieLang(); if(c&&c!==SRC) return c; try{var s=localStorage.getItem(STORE); if(s&&s!==SRC) return s;}catch(e){} return SRC; }
  function setCookie(v){
    var host=location.hostname, parts=host.split('.'), exp=v?'; max-age=31536000':'; expires=Thu, 01 Jan 1970 00:00:00 GMT';
    var val='googtrans='+(v?('/'+SRC+'/'+v):'')+'; path=/'+exp+'; SameSite=Lax';
    document.cookie=val;
    if (parts.length>1 && host!=='localhost') document.cookie=val+'; domain='+host;   // Google sometimes writes both forms
    if (parts.length>2) document.cookie=val+'; domain=.'+parts.slice(-2).join('.');
  }
  function applyDir(code){
    var h=document.documentElement, rtl=!!RTL[code];
    h.setAttribute('dir', rtl?'rtl':'ltr');
    h.classList.toggle('bdl-translated', code!==SRC);
  }

  // ---------- Google element ----------
  var gReady=false, pending=null;
  function combo(){ return document.querySelector('#bd-gt-host select.goog-te-combo'); }
  function fire(sel, val){
    sel.value=val;
    sel.dispatchEvent(new Event('change',{bubbles:true}));
  }
  function translateTo(code){
    var s=combo();
    if(!s){ pending=code; loadGoogle(); return; }
    fire(s, code);
    setTimeout(function(){ if(document.documentElement.className.indexOf('translated-')<0) fire(s, code); }, 600); // first change is sometimes ignored
  }
  var loading=false;
  function loadGoogle(){
    if (loading) return; loading=true;
    var host=document.createElement('div'); host.id='bd-gt-host'; host.setAttribute('aria-hidden','true'); document.body.appendChild(host);
    window.__bdGtInit=function(){
      try{ new google.translate.TranslateElement({pageLanguage:SRC, autoDisplay:false}, 'bd-gt-host'); }catch(e){ busy(false); return; }
      var t=0, iv=setInterval(function(){
        var s=combo();
        if (s && s.options.length>1){ clearInterval(iv); gReady=true; mergeFromGoogle(s); if(pending){var p=pending; pending=null; translateTo(p);} }
        else if (++t>100){ clearInterval(iv); if(!/translated-/.test(document.documentElement.className) && current()!==SRC) note('تعذّر تحميل الترجمة الآن · Translation could not load'); else busy(false); }
      },100);
    };
    var sc=document.createElement('script');
    sc.src='https://translate.google.com/translate_a/element.js?cb=__bdGtInit';
    sc.onerror=function(){ busy(false); note('تعذّر تحميل الترجمة الآن · Translation could not load'); };
    document.head.appendChild(sc);
  }
  var googleCodes=null;
  function mergeFromGoogle(s){
    googleCodes={};
    for (var i=0;i<s.options.length;i++){ var v=s.options[i].value; if(!v) continue; googleCodes[v]=s.options[i].text; if(CODES.indexOf(v)<0){ CODES.push(v); } }
    if (list) render(input.value);
  }
  // watch Google applying the translation, keep direction correct, clear the busy toast
  new MutationObserver(function(){
    var cls=document.documentElement.className;
    if (/translated-(ltr|rtl)/.test(cls)){ applyDir(current()); busy(false); }
  }).observe(document.documentElement,{attributes:true,attributeFilter:['class','lang']});

  // ---------- UI ----------
  var GLOBE='<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M3 12h18M12 3c2.6 2.6 3.9 5.6 3.9 9s-1.3 6.4-3.9 9c-2.6-2.6-3.9-5.6-3.9-9S9.4 5.6 12 3z"/></svg>';
  var SEARCH='<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" aria-hidden="true"><circle cx="11" cy="11" r="6.5"/><path d="M20 20l-4.2-4.2"/></svg>';
  var btn, panel, scrim, list, input, toast;

  function short(code){ return code===SRC ? '' : (BCP[code]||code).split('-')[0].toUpperCase(); }
  function label(){
    var c=current();
    btn.querySelector('.bdl-name').textContent = c===SRC ? 'اللغة' : names(c).nat;
    btn.querySelector('.bdl-code').textContent = short(c);
  }
  function build(){
    var slot=document.querySelector('[data-bd-lang]');
    var wrap=document.createElement('div');
    wrap.className='bdl notranslate'; wrap.setAttribute('translate','no');
    if(!slot){ wrap.className+=' bdl-float'; document.body.appendChild(wrap); } else { slot.appendChild(wrap); slot.classList.add('notranslate'); }
    wrap.innerHTML='<button type="button" class="bdl-btn" aria-haspopup="dialog" aria-expanded="false" aria-label="اللغة · Language">'+GLOBE+'<span class="bdl-name">اللغة</span><span class="bdl-code"></span></button>';
    btn=wrap.firstChild;

    scrim=document.createElement('div'); scrim.className='bdl-scrim';
    panel=document.createElement('div'); panel.className='bdl-panel notranslate'; panel.setAttribute('translate','no');
    panel.setAttribute('role','dialog'); panel.setAttribute('aria-label','اللغة · Language');
    panel.style.setProperty('--bdl-logo','url("'+BASE+'bd-logo.svg")');
    panel.innerHTML='<div class="bdl-head"><span class="bdl-mark"><i></i></span><div class="bdl-ttl"><b>اختاري لغتكِ</b><span>Choose your language</span></div><button type="button" class="bdl-x" aria-label="إغلاق · Close">×</button></div>'+
      '<label class="bdl-search">'+SEARCH+'<input type="search" autocomplete="off" spellcheck="false" placeholder="ابحثي عن لغة · Search a language"></label>'+
      '<div class="bdl-list" role="listbox"></div>'+
      '<div class="bdl-foot">النصّ الأصلي بالعربية، والترجمة تلقائية وقد لا تنقل كل المعنى.<span>Original text is Arabic; translations are automatic.</span></div>';
    toast=document.createElement('div'); toast.className='bdl-busy notranslate'; toast.setAttribute('translate','no'); toast.setAttribute('aria-live','polite');
    document.body.appendChild(scrim); document.body.appendChild(panel); document.body.appendChild(toast);
    list=panel.querySelector('.bdl-list'); input=panel.querySelector('input');

    btn.addEventListener('click',function(){ panel.classList.contains('on')?close():open(); });
    scrim.addEventListener('click',close);
    panel.querySelector('.bdl-x').addEventListener('click',close);
    input.addEventListener('input',function(){ render(input.value); });
    document.addEventListener('keydown',function(e){ if(e.key==='Escape'&&panel.classList.contains('on')) close(); });
    list.addEventListener('click',function(e){ var o=e.target.closest('.bdl-opt'); if(o){ choose(o.getAttribute('data-c')); } });
    window.addEventListener('resize',function(){ if(panel.classList.contains('on')) place(); });
    label();
  }
  function place(){
    if (window.innerWidth<700){ panel.style.top=panel.style.left=panel.style.right=''; return; }
    var r=btn.getBoundingClientRect(), w=360, left=Math.min(Math.max(12, r.left + r.width/2 - w/2), window.innerWidth-w-12);
    if (document.documentElement.dir!=='ltr') left=Math.max(12, Math.min(r.left, window.innerWidth-w-12));
    else left=Math.max(12, Math.min(r.right-w, window.innerWidth-w-12));
    panel.style.top=(r.bottom+10)+'px'; panel.style.left=left+'px'; panel.style.right='auto';
  }
  function open(){ loadGoogle(); render(''); input.value=''; place(); panel.classList.add('on'); scrim.classList.add('on'); btn.setAttribute('aria-expanded','true'); if(window.innerWidth>=700) setTimeout(function(){input.focus();},60); }
  function close(){ panel.classList.remove('on'); scrim.classList.remove('on'); btn.setAttribute('aria-expanded','false'); }

  function norm(s){ return (s||'').toLocaleLowerCase().normalize('NFD').replace(/[\u0300-\u036f\u064b-\u065f]/g,'').replace(/[أإآ]/g,'ا').replace(/ة/g,'ه').replace(/ى/g,'ي'); }
  function opt(code, cur){
    var n = code===SRC ? {nat:'العربية', ar:'النصّ الأصلي', en:'Original'} : names(code);
    var sub = code===SRC ? 'النصّ الأصلي · Original' : (n.ar && n.ar!==n.nat ? n.ar : '') + (n.en && n.en!==n.nat ? (n.ar && n.ar!==n.nat ?' · ':'')+n.en : '');
    return '<button type="button" role="option" class="bdl-opt" data-c="'+code+'"'+(code===cur?' aria-current="true"':'')+'><span class="n"><b dir="auto">'+n.nat+'</b>'+(sub?'<small>'+sub+'</small>':'')+'</span><span class="c">'+short(code||'ar').toLowerCase()+'</span></button>';
  }
  function available(c){ return !googleCodes || googleCodes[c]!=null; }
  function render(q){
    var cur=current(), html='', qn=norm(q.trim());
    var all=CODES.filter(function(c,i){ return c!==SRC && CODES.indexOf(c)===i && available(c); });
    if (qn){
      var hits=all.filter(function(c){ var n=names(c); return norm(n.nat+' '+n.ar+' '+n.en+' '+c+' '+(googleCodes&&googleCodes[c]||'')).indexOf(qn)>=0; });
      if ('العربيه arabic عربي'.indexOf(qn)>=0) html+=opt(SRC,cur);
      html+= hits.map(function(c){return opt(c,cur);}).join('') || (html?'':'<div class="bdl-empty">ما لقينا هاي اللغة · No language found</div>');
    } else {
      html+=opt(SRC,cur);
      html+='<div class="bdl-sec">الأكثر طلباً · Popular</div>'+PINNED.filter(available).map(function(c){return opt(c,cur);}).join('');
      var rest=all.filter(function(c){return PINNED.indexOf(c)<0;}).sort(function(a,b){ return names(a).en.localeCompare(names(b).en,'en'); });
      html+='<div class="bdl-sec">كل اللغات · All languages ('+(all.length+1)+')</div>'+rest.map(function(c){return opt(c,cur);}).join('');
    }
    list.innerHTML=html;
  }
  var tt;
  function busy(on,msg){ if(!toast) return; clearTimeout(tt); if(on){ toast.textContent=msg||'لحظة… · One moment…'; toast.classList.add('on'); tt=setTimeout(function(){busy(false);},9000);} else toast.classList.remove('on'); }
  function note(msg){ if(!toast) return; toast.textContent=msg; toast.classList.add('on'); clearTimeout(tt); tt=setTimeout(function(){busy(false);},4000); }

  function choose(code){
    close();
    if (code===current()) return;
    if (code===SRC){ setCookie(''); try{localStorage.removeItem(STORE);}catch(e){} }
    else { setCookie(code); try{localStorage.setItem(STORE,code);}catch(e){} }
    // Reload so Google applies the language cleanly to the whole page (switching live between
    // two translations is unreliable). Keep the visitor's scroll position.
    try{ sessionStorage.setItem('bd-lang-y', String(window.scrollY||0)); }catch(e){}
    busy(true, code===SRC ? 'نرجع للعربية… · Back to Arabic…' : 'نترجم الصفحة… · Translating…');
    applyDir(code); label();
    setTimeout(function(){ location.reload(); }, 120);
  }

  function restoreScroll(){
    try{ var y=sessionStorage.getItem('bd-lang-y'); if(y!=null){ sessionStorage.removeItem('bd-lang-y'); var go=function(){ window.scrollTo(0,+y); }; go(); setTimeout(go,400); setTimeout(go,1500); } }catch(e){}
  }
  function protectKeep(){
    var words=Object.keys(KEEP); if(!words.length) return;
    var re=new RegExp(words.map(function(w){return w.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');}).join('|'),'g');
    var w=document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {acceptNode:function(n){
      var p=n.parentNode; if(!p||/^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA|OPTION)$/.test(p.nodeName)) return 2;
      if(p.closest && p.closest('.bdl,.bdl-panel,.bdl-busy')) return 2;
      re.lastIndex=0; return re.test(n.nodeValue)?1:2; }});
    var nodes=[], n; while((n=w.nextNode())) nodes.push(n);
    nodes.forEach(function(t){ t.nodeValue=t.nodeValue.replace(re,function(m){return KEEP[m];}); });
    if (KEEP[document.title]===undefined) document.title=document.title.replace(re,function(m){return KEEP[m];});
  }
  function init(){
    build();
    restoreScroll();
    var c=current();
    if (c!==SRC){                          // a language was chosen (this page, another /bndn/ page, or an earlier visit)
      if(getCookieLang()!==c) setCookie(c);
      protectKeep(); applyDir(c); busy(true,'نترجم الصفحة… · Translating…'); loadGoogle();
      // Google applies the cookie by itself on load; nudge it only if it has not started after a moment
      [2500,6000,11000].forEach(function(ms){ setTimeout(function(){ if(!/translated-/.test(document.documentElement.className)) translateTo(c); }, ms); });
    }
  }
  if (document.readyState==='loading') document.addEventListener('DOMContentLoaded',init); else init();
  window.bdLang={set:choose, current:current};
})();
